// LivePackagerConfig contains configuration for the live packager.
type LivePackagerConfig struct {
	StreamID        string
	InputURL        string
	OutputBucket    string
	OutputPrefix    string
	SegmentDuration float64
	PartDuration    float64
	Presets         []string
	EnableLLHLS     bool
	EnableDRM       bool
	DVRWindowSize   int
	AWSRegion       string
	
	// Advanced settings
	GOPSize         int     // Keyframe interval in frames
	BufferSize      string  // FFmpeg buffer size
	MaxMuxingQueue  int     // FFmpeg max muxing queue size
}

// LivePackager handles real-time CMAF packaging of live streams using Shaka Packager.
type LivePackager struct {
	config    *LivePackagerConfig
	logger    *slog.Logger
	s3Client  *s3.Client
	
	// State
	active    atomic.Bool
	startTime time.Time
	stats     *StreamStats
	statsMu   sync.RWMutex
	
	// Processes
	ffmpegCmd   *exec.Cmd
	shakaCmd    *exec.Cmd
	
	// Output management
	localOutputDir string
	pipeDir        string
	uploadQueue    chan string
	uploadWG       sync.WaitGroup
}

// NewLivePackager creates a new live packager.
func NewLivePackager(cfg *LivePackagerConfig, logger *slog.Logger) (*LivePackager, error) {
	// Set defaults
	if cfg.SegmentDuration == 0 {
		cfg.SegmentDuration = 4.0
	}
	if cfg.PartDuration == 0 && cfg.EnableLLHLS {
		cfg.PartDuration = 0.5
	}
	if cfg.GOPSize == 0 {
		cfg.GOPSize = int(cfg.SegmentDuration * 30) // Assuming 30fps
	}
	if cfg.BufferSize == "" {
		cfg.BufferSize = "4M"
	}

	// Create AWS config
	awsCfg, err := config.LoadDefaultConfig(context.Background(),
		config.WithRegion(cfg.AWSRegion),
	)
	if err != nil {
		return nil, fmt.Errorf("failed to load AWS config: %w", err)
	}

	// Create local output directory
	localOutputDir := filepath.Join(os.TempDir(), "live", cfg.StreamID)
	if err := os.MkdirAll(localOutputDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create output directory: %w", err)
	}

	// Create pipe directory
	pipeDir := filepath.Join(os.TempDir(), "pipes", cfg.StreamID)
	if err := os.MkdirAll(pipeDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create pipe directory: %w", err)
	}

	return &LivePackager{
		config:         cfg,
		logger:         logger,
		s3Client:       s3.NewFromConfig(awsCfg),
		stats:          &StreamStats{},
		localOutputDir: localOutputDir,
		pipeDir:        pipeDir,
		uploadQueue:    make(chan string, 100),
	}, nil
}

// Start starts the live packager (FFmpeg -> Pipes -> Shaka).
func (p *LivePackager) Start(ctx context.Context) error {
	p.startTime = time.Now()

	// 1. Setup Named Pipes
	presets := p.config.Presets
	if len(presets) == 0 {
		presets = []string{"1080p", "720p", "480p"}
	}

	// Create pipes for video presets
	for i := range presets {
		pipePath := filepath.Join(p.pipeDir, fmt.Sprintf("stream_%d.ts", i))
		if err := syscall.Mkfifo(pipePath, 0600); err != nil && !os.IsExist(err) {
			return fmt.Errorf("failed to create pipe %s: %w", pipePath, err)
		}
	}
	// Create pipe for audio
	audioPipePath := filepath.Join(p.pipeDir, "audio.ts")
	if err := syscall.Mkfifo(audioPipePath, 0600); err != nil && !os.IsExist(err) {
		return fmt.Errorf("failed to create audio pipe: %w", err)
	}

	// 2. Start the S3 uploader
	p.uploadWG.Add(1)
	go p.uploadWorker(ctx)

	// 3. Start Shaka Packager (Consumer)
	shakaArgs := p.buildShakaArgs()
	p.logger.Debug("starting shaka packager", "args", strings.Join(shakaArgs, " "))
	p.shakaCmd = exec.CommandContext(ctx, "packager", shakaArgs...)
	p.shakaCmd.Stdout = os.Stdout
	p.shakaCmd.Stderr = os.Stderr // Capture shaka logs

	if err := p.shakaCmd.Start(); err != nil {
		return fmt.Errorf("failed to start shaka packager: %w", err)
	}

	// 4. Start FFmpeg (Producer)
	ffmpegArgs := p.buildFFmpegArgs()
	p.logger.Debug("starting ffmpeg", "args", strings.Join(ffmpegArgs, " "))
	p.ffmpegCmd = exec.CommandContext(ctx, "ffmpeg", ffmpegArgs...)
	
	// Capture FFmpeg stderr for monitoring
	stderr, err := p.ffmpegCmd.StderrPipe()
	if err != nil {
		_ = p.shakaCmd.Process.Kill()
		return fmt.Errorf("failed to get ffmpeg stderr pipe: %w", err)
	}

	if err := p.ffmpegCmd.Start(); err != nil {
		_ = p.shakaCmd.Process.Kill()
		return fmt.Errorf("failed to start ffmpeg: %w", err)
	}

	p.active.Store(true)

	// Monitor FFmpeg in background
	go p.monitorFFmpeg(ctx, stderr)

	// Start file watcher for new segments generated by Shaka
	go p.watchSegments(ctx)

	// Wait for processes
	ffmpegErr := p.ffmpegCmd.Wait()
	p.logger.Info("ffmpeg finished", "error", ffmpegErr)
	
	// If FFmpeg stops, we should stop Shaka (it might hang waiting for input)
	if p.shakaCmd.Process != nil {
		_ = p.shakaCmd.Process.Signal(os.Interrupt)
	}
	shakaErr := p.shakaCmd.Wait()
	p.logger.Info("shaka finished", "error", shakaErr)

	// Cleanup
	p.active.Store(false)
	close(p.uploadQueue)
	p.uploadWG.Wait()
	os.RemoveAll(p.pipeDir)
	os.RemoveAll(p.localOutputDir)

	if ffmpegErr != nil {
		return fmt.Errorf("ffmpeg exited with error: %w", ffmpegErr)
	}
	if shakaErr != nil {
		return fmt.Errorf("shaka exited with error: %w", shakaErr)
	}

	return nil
}

// Stop stops the live packager.
func (p *LivePackager) Stop(ctx context.Context) error {
	// Stop FFmpeg first (producer)
	if p.ffmpegCmd != nil && p.ffmpegCmd.Process != nil {
		p.ffmpegCmd.Process.Signal(os.Interrupt)
	}
	
	// Shaka should exit once pipes close, but we can signal it too
	if p.shakaCmd != nil && p.shakaCmd.Process != nil {
		time.Sleep(2 * time.Second) // Give FFmpeg time to close pipes cleanly
		p.shakaCmd.Process.Signal(os.Interrupt)
	}

	return nil
}

func (p *LivePackager) IsActive() bool {
	return p.active.Load()
}

func (p *LivePackager) GetStats() *StreamStats {
	p.statsMu.RLock()
	defer p.statsMu.RUnlock()
	stats := *p.stats
	stats.Duration = time.Since(p.startTime)
	return &stats
}

// buildFFmpegArgs builds command to output to Named Pipes.
func (p *LivePackager) buildFFmpegArgs() []string {
	args := []string{
		"-y", "-hide_banner", "-loglevel", "warning", "-stats",
	}

	// Input
	if strings.HasPrefix(p.config.InputURL, "srt://") {
		args = append(args, "-fflags", "+genpts+discardcorrupt", "-i", p.config.InputURL)
	} else {
		args = append(args, "-i", p.config.InputURL)
	}

	presets := p.config.Presets
	if len(presets) == 0 {
		presets = []string{"1080p", "720p", "480p"}
	}

	// Filter Complex
	filterComplex := p.buildFilterComplex(presets)
	if filterComplex != "" {
		args = append(args, "-filter_complex", filterComplex)
	}

	// Output streams to pipes
	for i, preset := range presets {
		bitrate := getPresetBitrate(preset)
		pipePath := filepath.Join(p.pipeDir, fmt.Sprintf("stream_%d.ts", i))

		args = append(args,
			"-map", fmt.Sprintf("[v%d]", i),
			fmt.Sprintf("-c:v:%d", i), "libx264",
			fmt.Sprintf("-b:v:%d", i), bitrate,
			fmt.Sprintf("-maxrate:v:%d", i), bitrate,
			fmt.Sprintf("-bufsize:v:%d", i), p.config.BufferSize,
			fmt.Sprintf("-preset:%d", i), "veryfast",
			fmt.Sprintf("-profile:v:%d", i), "main",
			fmt.Sprintf("-g:%d", i), strconv.Itoa(p.config.GOPSize),
			fmt.Sprintf("-keyint_min:%d", i), strconv.Itoa(p.config.GOPSize),
			fmt.Sprintf("-sc_threshold:%d", i), "0",
			"-f", "mpegts", // Output format for pipe
			pipePath,
		)
	}

	// Audio output to pipe
	audioPipePath := filepath.Join(p.pipeDir, "audio.ts")
	args = append(args,
		"-map", "0:a",
		"-c:a", "aac", "-b:a", "128k", "-ac", "2", "-ar", "48000",
		"-f", "mpegts",
		audioPipePath,
	)

	return args
}

// buildShakaArgs builds the Shaka Packager command to consume pipes and output HLS/CMAF.
func (p *LivePackager) buildShakaArgs() []string {
	args := []string{}
	presets := p.config.Presets
	if len(presets) == 0 {
		presets = []string{"1080p", "720p", "480p"}
	}

	// Inputs
	for i, _ := range presets {
		pipePath := filepath.Join(p.pipeDir, fmt.Sprintf("stream_%d.ts", i))
		streamSelector := fmt.Sprintf(
			"in=%s,stream=video,output=%s/stream_%d.m4s,init_segment=%s/init_%d.mp4,playlist_name=%s/stream_%d.m3u8,iframe_playlist_name=%s/iframe_%d.m3u8",
			pipePath, p.localOutputDir, i, p.localOutputDir, i, p.localOutputDir, i, p.localOutputDir, i,
		)
		args = append(args, streamSelector)
	}

	// Audio Input
	audioPipePath := filepath.Join(p.pipeDir, "audio.ts")
	args = append(args, fmt.Sprintf(
		"in=%s,stream=audio,output=%s/audio.m4s,init_segment=%s/init_audio.mp4,playlist_name=%s/audio.m3u8,hls_group_id=audio,hls_name=ENGLISH",
		audioPipePath, p.localOutputDir, p.localOutputDir, p.localOutputDir,
	))

	// Global Flags
	args = append(args,
		"--enable_raw_key_encryption",
		"--segment_duration", fmt.Sprintf("%f", p.config.SegmentDuration),
		"--hls_master_playlist_output", filepath.Join(p.localOutputDir, "master.m3u8"),
		"--hls_playlist_type", "LIVE",
		"--time_shift_buffer_depth", fmt.Sprintf("%d", p.config.DVRWindowSize*int(p.config.SegmentDuration)),
	)

	if p.config.EnableLLHLS {
		args = append(args, "--low_latency_dash_mode") // Shaka uses this for LL-HLS optimization too
	}

	return args
}

// buildFilterComplex builds the FFmpeg filter complex for multi-bitrate encoding.
func (p *LivePackager) buildFilterComplex(presets []string) string {
	if len(presets) == 0 { return "" }
	var filters []string
	splitOut := ""
	for i := range presets { splitOut += fmt.Sprintf("[v%d]", i) }
	filters = append(filters, fmt.Sprintf("[0:v]split=%d%s", len(presets), splitOut))

	for i, preset := range presets {
		res := getPresetResolution(preset)
		filters = append(filters,
			fmt.Sprintf("[v%d]scale=%d:%d:force_original_aspect_ratio=decrease,pad=%d:%d:(ow-iw)/2:(oh-ih)/2[v%d]",
				i, res.width, res.height, res.width, res.height, i),
		)
	}
	return strings.Join(filters, ";")
}

