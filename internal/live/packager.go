// watchSegments (Same as before but looking for Shaka output)
func (p *LivePackager) watchSegments(ctx context.Context) {
	// Implementation unchanged, logic for picking up .m4s/.ts/.m3u8 is same
	ticker := time.NewTicker(200 * time.Millisecond) // Faster tick for LL-HLS
	defer ticker.Stop()
	uploadedFiles := make(map[string]bool)

	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			files, err := os.ReadDir(p.localOutputDir)
			if err != nil { continue }
			for _, file := range files {
				if file.IsDir() { continue }
				name := file.Name()
				if uploadedFiles[name] { continue }
				
				// Queue for upload
				fullPath := filepath.Join(p.localOutputDir, name)
				select {
				case p.uploadQueue <- fullPath:
					uploadedFiles[name] = true
				default:
				}
			}
		}
	}
}

// uploadWorker (Same as before)
func (p *LivePackager) uploadWorker(ctx context.Context) {
	defer p.uploadWG.Done()
	for {
		select {
		case filePath, ok := <-p.uploadQueue:
			if !ok { return }
			p.uploadFile(ctx, filePath)
		case <-ctx.Done():
			return
		}
	}
}

func (p *LivePackager) uploadFile(ctx context.Context, filePath string) error {
	// Same implementation as original, just handles s3 upload
	file, err := os.Open(filePath)
	if err != nil { return err }
	defer file.Close()

	fileName := filepath.Base(filePath)
	key := fmt.Sprintf("%s/%s", p.config.OutputPrefix, fileName)
	
	// ... (S3 PutObject logic unchanged) ...
	// Placeholder for brevity, assume standard S3 upload with proper Content-Type
	_, err = p.s3Client.PutObject(ctx, &s3.PutObjectInput{
		Bucket: aws.String(p.config.OutputBucket),
		Key:    aws.String(key),
		Body:   file,
	})
	return err
}

